const assert=require('node:assert/strict');
const C=require('../shared/obsidian_ui/plugin-src/core.js');
assert.deepEqual(C.previous('2026-03-01','2026-03-31'),['2026-01-29','2026-02-28']);
assert.equal(C.bucket('2026-09-27','week'),'2026-09-21');
const rows=[{date:'2026-09-01',value:10},{date:'2026-09-03',value:20}];
assert.equal(C.aggregate(rows,'2026-09-01','2026-09-03','day')[1].value,null);
assert.equal(C.aggregate(rows,'2026-09-01','2026-09-30','month','sum')[0].value,30);
assert.equal(C.aggregate(rows,'2026-09-01','2026-09-30','month','mean')[0].value,15);
assert.equal(C.aggregate(rows,'2026-09-01','2026-09-30','month','last')[0].value,20);
assert.equal(C.aggregate([{date:'2026-09-02',value:0}],'2026-09-02','2026-09-02','day')[0].value,0);
assert.equal(C.valid('2026-02-30'),false);
assert.equal(C.add('2026-03-29',1),'2026-03-30');
assert.deepEqual(C.paired([{date:'2026-09-01',a:5,b:null},{date:'2026-09-02',a:null,b:9}],'a','b',1,'2026-09-01','2026-09-03'),[[5,9,'2026-09-02']]);
assert.equal(C.rolling(rows,7)[1].value,15);
console.log('Interactive aggregation: 11 assertions passed');
assert.equal(C.aggregate([1,2,3,100,99].map(value=>({date:'2026-09-01',value})),'2026-09-01','2026-09-30','month','median')[0].value,3);
assert.equal(C.bucket('2026-05-31','quarter'),'2026-04-01');
assert.equal(C.next('2026-10-01','quarter'),'2027-01-01');
assert.deepEqual(C.aggregate([{date:'2026-02-01',value:5},{date:'2026-04-01',value:7}],'2026-01-01','2026-06-30','quarter').map(p=>p.value),[5,7]);
assert.deepEqual(C.standardize([1,null,3]),[-1,null,1]);
assert.ok(Math.abs(C.spearman([[1,1],[1,1],[2,2]])-1)<1e-12);
assert.equal(C.spearman([[1,1],[1,2]]),null);
